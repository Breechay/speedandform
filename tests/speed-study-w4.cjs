'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const {data,note,MARK,transform}=require('../scripts/update-speed-study-w4.cjs');
const file=path.join(__dirname,'../labs/speed-that-endures/index.html');
const html=fs.readFileSync(file,'utf8');
assert(html.includes(MARK));
assert.equal(transform(html),html,'reapplying the update is a no-op');
assert.equal(data.jose.distanceMiles,5);assert.equal(data.hope.distanceMiles,5);
assert.equal(data.jose.durationSeconds,2020.8);assert.equal(data.hope.durationSeconds,2057.9);
assert(Math.abs(data.hope.mileSplitsSeconds.reduce((a,b)=>a+b,0)-2057.9)<1e-7);
assert(data.hope.mileSplitsSeconds.every(s=>s>=405&&s<=420));
assert(Math.abs(Math.max(...data.hope.mileSplitsSeconds)-Math.min(...data.hope.mileSplitsSeconds)-5.2)<1e-7);
assert.equal(data.hope.effort,null,'a coach question is not an athlete-confirmed effort');
assert.equal(data.jose.mileSplitsSeconds,null,'aggregate is not a split trace');
assert.equal(data.next.floatSeconds,120,'2 min, not 2 miles');
const match=html.match(/const evidence\s*=\s*\{[\s\S]*?\n\};(?=\n\n\/\* ---------- lab note inspection)/);
assert(match,'interactive evidence object present');
const evidence=vm.runInNewContext(match[0]+'\nevidence',{}, {timeout:1000});
assert.equal(JSON.stringify(evidence.w4),JSON.stringify(note));
assert.equal(evidence.w2.j.out,'6:37 · 6:41 · 6:35');
assert.equal(evidence.w3.j.out,'6:42 · 6:43 · 6:43 · 6:43');
assert.equal(evidence.w3.h.out,'6:50 · 6:50 · 6:53 · 6:50');
assert(!evidence.w4.j.strava&&!evidence.w4.h.strava,'do not relabel old activity links');
assert(/id="note-w4">[\s\S]*?<span class="st">Recorded<\/span>/.test(html));
assert(!/SEP 15 · W4<\/span><b>5 CONT\.<\/b><small>FUTURE/.test(html));
assert(html.includes('In progress · updated Sep 17'));
assert(html.includes('In progress · last updated Sep 17 2026'));
assert(html.includes('"dateModified":"2026-09-17"'));
assert(!html.includes('The status line writes itself'));
assert(html.includes('id="w4-read"')&&html.includes('data-filed="2026-09-15"'));
assert(html.includes('3 × 10 min')&&html.includes('2 min floats'));
assert(!html.includes('right hip flexor'),'private health detail not published');
assert(!html.includes('Ant831990'),'no unrelated account information');
assert(!html.includes('IMG_7384'),'raw private screenshots not embedded');
for(const m of html.matchAll(/<script(?: [^>]*)?>([\s\S]*?)<\/script>/g)) {
 if(m[0].includes('application/ld+json')) JSON.parse(m[1]);
 else new vm.Script(m[1]);
}
console.log('Speed study W4: measurements, provenance, prior evidence, syntax and idempotency pass.');
