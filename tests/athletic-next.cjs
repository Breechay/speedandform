'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..'),read=f=>fs.readFileSync(path.join(root,f),'utf8');
const {makePage,makeThanks}=require('../scripts/build-athletic-next.cjs');
const data=JSON.parse(read('the-athletic-life/next/items.json'));
const items=data.sections.flatMap(s=>s.items);
assert.deepEqual(data.sections.map(s=>s.id).filter(id=>id!=='released'),['testing','next','ideas'],'Three states, in order, then what has shipped');
assert.ok(!data.sections.some(s=>s.id==='released'&&!s.items.length),'Released appears only when something has shipped');
for(const item of items)for(const key of ['title','line'])assert.ok(item[key]?.trim(),item.title+': needs '+key);
assert.ok(data.sections[1].items.every(item=>item.when?.trim()),'Every up-next item says when');
assert.equal(data.sections[0].when,'Next update','Testing carries one timing');
const words=JSON.stringify(data);
assert.doesNotMatch(words,/—/,'No em dashes');
assert.doesNotMatch(words,/Brice/,'No coach name on an athlete-facing page');
assert.equal(data.sections[2].when,'No date','Ideas carry no date');
assert.ok(data.sections[2].items.every(item=>!item.when),'No idea carries its own date');
assert.match(items.find(item=>item.title==='Garmin').when,/Waiting on Garmin/,'Garmin stays conditional');
const athleteRuns=items.find(item=>item.title==='Athlete runs');
assert.equal(athleteRuns.prototype.href,'/the-athletic-life/next/prototypes/FORM_Home_Athlete_Runs.html','Prototype has a stable public route');
assert.equal(athleteRuns.when,'Concept ready · Timing open','The concept has no invented ship date');
const original=fs.readFileSync(path.join(root,athleteRuns.prototype.href.slice(1)));
assert.equal(crypto.createHash('sha256').update(original).digest('hex'),'9c84995e939f92668fd2636d2dc56e4c728a022192973cda587347d87e47e7d4','Original self-contained mockup is preserved unchanged');
assert.match(original.toString('utf8'),/id="team-runs-title">Runs from the team/,'Download contains the Athlete Runs interaction');
const page=makePage(data);
assert.match(page,/Explore the mockup<\/a>/,'Public page offers a mockup preview');
assert.match(page,/download="FORM_Home_Athlete_Runs.html">Download HTML<\/a>/,'Public page offers the original HTML download');
assert.match(page,/Names, runs and attendance are illustrative, not live/,'Prototype is not mistaken for live data');
assert.match(page,/href="#wn-ask">Suggest a change<\/a>/,'Prototype invites feedback through the existing suggestion form');
assert.match(read('the-athletic-life/next/index.html'),/Explore the mockup<\/a>/,'Generated public page includes the preview link');
assert.match(read('the-athletic-life/next/index.html'),/download="FORM_Home_Athlete_Runs.html">Download HTML<\/a>/,'Generated public page includes the download link');
assert.equal(read('the-athletic-life/next/thanks/index.html'),makeThanks(),'Thanks page is generated');
assert.match(read('the-athletic-life/next/index.html'),/<title>What's next \| Speed &amp; Form<\/title>/,'Generated page is committed');
assert.match(page,/name="whats-next"[^>]*action="\/the-athletic-life\/next\/thanks\/"[^>]*data-netlify="true"/,'Static form posts to the thanks page');
assert.match(page,/name="form-name" value="whats-next"/,'Netlify form name');
assert.match(page,/netlify-honeypot="company"/,'Spam trap');
assert.match(read('sitemap.xml'),/the-athletic-life\/next\/<\/loc>/,'Listed once public');
assert.doesNotMatch(read('sitemap.xml'),/next\/thanks/,'Thanks page stays unlisted');
assert.match(read('scripts/build-athletic-life.cjs'),/href="\/the-athletic-life\/next\/"/,'Founding brief links here');
assert.match(read('scripts/build-athletic-research.cjs'),/next\/">What's next/,'Collection links here');
console.log("What's next: states, copy guards, form wiring and collection links verified");
